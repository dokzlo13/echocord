"""Generate the original fixed 48 kHz limiter peak-detector coefficients.

Uses only Python's standard library. This is a sidechain interpolator, not an
audio resampler or a claim of compliance with a true-peak measurement standard.
"""

import argparse
from decimal import Decimal, localcontext
from pathlib import Path

PI = Decimal("3.141592653589793238462643383279502884197169399375105820974944592307816406286")


def bessel_i0(value: Decimal) -> Decimal:
    term = total = Decimal(1)
    square = value * value / 4
    for order in range(1, 100):
        term *= square / (order * order)
        updated = total + term
        if updated == total:
            return total
        total = updated
    raise ArithmeticError("Bessel series did not converge")


def sine(value: Decimal) -> Decimal:
    value %= 2 * PI
    if value > PI:
        value -= 2 * PI
    elif value < -PI:
        value += 2 * PI
    term = total = value
    for order in range(1, 100):
        term *= -value * value / ((2 * order) * (2 * order + 1))
        updated = total + term
        if updated == total:
            return total
        total = updated
    raise ArithmeticError("Sine series did not converge")


def generate_at_current_precision() -> str:
    radius = 32
    beta = Decimal("8.6")
    normalization = bessel_i0(beta)
    window = [
        bessel_i0(beta * max(Decimal(0), 1 - (Decimal(k) / radius) ** 2).sqrt())
        / normalization
        for k in range(-radius, radius + 1)
    ]
    lines = [
        "// Generated by: python scripts/generate-limiter-coefficients.py",
        "// Original 65-tap sinc/Kaiser (beta 8.6) phases 1/8 through 7/8.",
        "// Phase zero uses the exact input sample and needs no coefficients.",
        "#[rustfmt::skip]",
        "pub(super) const COEFFICIENTS: [[f64; 65]; 7] = [",
    ]
    for phase in range(1, 8):
        coefficients = []
        for k, weight in zip(range(-radius, radius + 1), window):
            angle = PI * (Decimal(phase) / 8 - k)
            coefficients.append(sine(angle) / angle * weight)
        total = sum(coefficients)
        coefficients = [coefficient / total for coefficient in coefficients]
        lines.append("    [")
        for start in range(0, len(coefficients), 4):
            lines.append(
                "        "
                + ", ".join(repr(float(value)) for value in coefficients[start : start + 4])
                + ","
            )
        lines.append("    ],")
    lines.append("];\n")
    return "\n".join(lines)


def generate() -> str:
    # Avoid platform libm rounding differences in generated source. Round each
    # high-precision result to f64 once, then emit its shortest round-trip form.
    with localcontext() as context:
        context.prec = 70
        return generate_at_current_precision()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="reject stale generated output")
    args = parser.parse_args()
    output = (
        Path(__file__).resolve().parents[1]
        / "crates/core/src/limiter/coefficients.rs"
    )
    expected = generate().encode("utf-8")
    if args.check:
        if not output.is_file() or output.read_bytes() != expected:
            raise SystemExit("Limiter coefficients are stale; run this script without --check.")
    else:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_bytes(expected)


if __name__ == "__main__":
    main()
